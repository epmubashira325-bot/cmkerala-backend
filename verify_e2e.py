"""
Verification Script: Complete 17-Step End-to-End Workflow Audit
CM Kerala – Chief Minister's Public Grievance Redressal Portal
"""
import os
import django

os.environ.setdefault('DJANGO_SETTINGS_MODULE', 'config.settings')
django.setup()

from django.conf import settings
if 'testserver' not in settings.ALLOWED_HOSTS:
    settings.ALLOWED_HOSTS.append('testserver')

from django.core.files.uploadedfile import SimpleUploadedFile
from rest_framework.test import APIClient
from accounts.models import User
from departments.models import Department
from grievances.models import Grievance, ActionTakenReport, CitizenFeedback


def run_e2e_workflow_audit():
    print("=" * 70)
    print("CM KERALA E2E WORKFLOW INTEGRATION AUDIT")
    print("=" * 70)

    client = APIClient()

    # Step 0: Ensure Public Works Department exists
    pwd_dept, _ = Department.objects.get_or_create(
        code="PWD",
        defaults={
            "name": "Public Works Department",
            "description": "State roads, bridges, and infrastructure maintenance",
            "is_active": True
        }
    )
    print(f"[OK] Department verified: {pwd_dept.code} - {pwd_dept.name}")

    # Step 0b: Create Fictional Demo Accounts
    # 1. Citizen
    citizen_email = "citizen@example.com"
    citizen_pass = "CitizenDemoPass123!"
    citizen, created = User.objects.get_or_create(
        email=citizen_email,
        defaults={
            "full_name": "Smt. Lakshmi Devi",
            "role": User.Role.CITIZEN,
            "mobile_number": "9847012345",
            "is_active": True,
        }
    )
    citizen.set_password(citizen_pass)
    citizen.save()

    # 2. CMO Admin
    cmo_email = "cmo@example.com"
    cmo_pass = "CMODemoPass123!"
    cmo_admin, created = User.objects.get_or_create(
        email=cmo_email,
        defaults={
            "full_name": "Dr. K. S. Rajeev (CMO Secretary)",
            "role": User.Role.CMO_ADMIN,
            "mobile_number": "9447010760",
            "is_active": True,
        }
    )
    cmo_admin.set_password(cmo_pass)
    cmo_admin.save()

    # 3. PWD Officer
    officer_email = "officer.pwd@example.com"
    officer_pass = "OfficerDemoPass123!"
    officer, created = User.objects.get_or_create(
        email=officer_email,
        defaults={
            "full_name": "Er. P. Narayanan (Executive Engineer PWD)",
            "role": User.Role.OFFICER,
            "department": pwd_dept,
            "mobile_number": "9446055555",
            "is_active": True,
        }
    )
    officer.set_password(officer_pass)
    officer.save()
    print("[OK] Demo accounts created & synchronized.")

    # -------------------------------------------------------------
    # Step 1: Citizen logs in
    # -------------------------------------------------------------
    res_login = client.post('/api/v1/auth/login/', {'email': citizen_email, 'password': citizen_pass})
    assert res_login.status_code == 200, f"Citizen login failed: {res_login.data}"
    citizen_token = res_login.data['access']
    print("[1/17] Citizen logged in successfully. Access token obtained.")

    # -------------------------------------------------------------
    # Step 2: Citizen submits damaged-road complaint
    # Step 3: Gemini analyzes complaint
    # Step 4: System generates reference number
    # -------------------------------------------------------------
    client.credentials(HTTP_AUTHORIZATION=f'Bearer {citizen_token}')
    photo_file = SimpleUploadedFile("road_damage.jpg", b"fake_image_bytes_road_damage", content_type="image/jpeg")

    grievance_payload = {
        'district': 'THIRUVANANTHAPURAM',
        'category': 'Public Works & Infrastructure',
        'subject': 'Severe crater pothole on MC Road near Venjaramoodu',
        'description': 'A massive 2-foot trench has opened across the main carriageway causing multiple two-wheeler accidents. Urgent resurfacing needed.',
        'include_ai_triage': 'true',
        'attachments': [photo_file]
    }
    res_submit = client.post('/api/v1/citizen/grievances/', grievance_payload, format='multipart')
    assert res_submit.status_code == 201, f"Submission failed: {res_submit.data}"
    grievance_data = res_submit.data
    grievance_id = grievance_data['id']
    ref_num = grievance_data['reference_number']
    print(f"[2-4/17] Grievance submitted. Ref Number generated by DB: {ref_num}")
    print(f"         Status: {grievance_data['status']}, District: {grievance_data['district']}")

    # -------------------------------------------------------------
    # Step 5: CMO logs in
    # -------------------------------------------------------------
    client.credentials()  # Clear auth
    res_cmo_login = client.post('/api/v1/auth/login/', {'email': cmo_email, 'password': cmo_pass})
    assert res_cmo_login.status_code == 200, f"CMO login failed: {res_cmo_login.data}"
    cmo_token = res_cmo_login.data['access']
    client.credentials(HTTP_AUTHORIZATION=f'Bearer {cmo_token}')
    print("[5/17] CMO logged in successfully.")

    # -------------------------------------------------------------
    # Step 6: CMO views the complaint
    # Step 7: CMO reviews AI recommendations
    # -------------------------------------------------------------
    res_cmo_view = client.get(f'/api/v1/cmo/grievances/{grievance_id}/')
    assert res_cmo_view.status_code == 200, f"CMO view failed: {res_cmo_view.data}"
    cmo_dossier = res_cmo_view.data
    print(f"[6-7/17] CMO viewed complaint dossier.")
    print(f"         AI Suggestions Recorded: {cmo_dossier.get('ai_suggestions') is not None}")

    # -------------------------------------------------------------
    # Step 8: CMO assigns Public Works Department
    # Step 9: CMO selects an officer belonging to PWD
    # -------------------------------------------------------------
    assign_payload = {
        'department_id': str(pwd_dept.id),
        'officer_id': str(officer.id),
        'due_date': '2026-11-20',
        'remarks': 'Priority field inspection directed by Chief Minister Secretariat'
    }
    res_assign = client.post(f'/api/v1/cmo/grievances/{grievance_id}/assign/', assign_payload)
    assert res_assign.status_code == 200, f"Assignment failed: {res_assign.data}"

    # Verify status progressed
    g_after_assign = Grievance.objects.get(id=grievance_id)
    assert g_after_assign.status == Grievance.Status.IN_PROGRESS, f"Status expected IN_PROGRESS, got {g_after_assign.status}"
    assert g_after_assign.assigned_department == pwd_dept
    assert g_after_assign.assigned_officer == officer
    print(f"[8-9/17] Assigned to PWD & Officer {officer.full_name}. Status auto-transitioned to {g_after_assign.status}.")

    # -------------------------------------------------------------
    # Step 10: Officer logs in
    # -------------------------------------------------------------
    client.credentials()
    res_off_login = client.post('/api/v1/auth/login/', {'email': officer_email, 'password': officer_pass})
    assert res_off_login.status_code == 200, f"Officer login failed: {res_off_login.data}"
    officer_token = res_off_login.data['access']
    client.credentials(HTTP_AUTHORIZATION=f'Bearer {officer_token}')
    print("[10/17] PWD Officer logged in successfully.")

    # -------------------------------------------------------------
    # Step 11: Officer sees assigned complaint in queue
    # -------------------------------------------------------------
    res_off_list = client.get('/api/v1/officer/grievances/')
    assert res_off_list.status_code == 200
    off_queue = res_off_list.data.get('results', res_off_list.data)
    assigned_ids = [item['id'] for item in off_queue]
    assert grievance_id in assigned_ids, "Grievance missing from officer's assigned queue"
    print(f"[11/17] Officer identified assigned grievance {ref_num} in queue.")

    # -------------------------------------------------------------
    # Step 12: Officer adds investigation remarks
    # -------------------------------------------------------------
    remark_payload = {'remarks': 'Conducted site inspection at Venjaramoodu. Cold-mix patching materials mobilized.'}
    res_remark = client.post(f'/api/v1/officer/grievances/{grievance_id}/remarks/', remark_payload)
    assert res_remark.status_code == 200
    print("[12/17] Officer posted field investigation note into audit history.")

    # -------------------------------------------------------------
    # Step 13: Officer uploads an action-taken report
    # -------------------------------------------------------------
    atr_proof = SimpleUploadedFile("completion_atr.pdf", b"%PDF-1.4 mock signed completion certificate", content_type="application/pdf")
    atr_payload = {
        'investigation_description': 'Site verified with junior engineer. Sub-base re-compacted and 50mm dense bituminous macadam laid.',
        'resolution_details': 'Carriageway restored to motorable grade. Traffic flow normalized without bottleneck.',
        'report_attachment': atr_proof
    }
    res_atr = client.post(f'/api/v1/officer/grievances/{grievance_id}/reports/', atr_payload, format='multipart')
    assert res_atr.status_code == 201, f"ATR submission failed: {res_atr.data}"
    report_id = res_atr.data['report']['id']
    print(f"[13/17] Officer submitted ATR {report_id}. Status: PENDING review by CMO.")

    # -------------------------------------------------------------
    # Step 14: CMO reviews the report
    # Step 15: CMO approves the report -> Grievance becomes RESOLVED
    # -------------------------------------------------------------
    client.credentials(HTTP_AUTHORIZATION=f'Bearer {cmo_token}')
    review_payload = {
        'decision': 'APPROVED',
        'remarks': 'Remediation verified with district collectorate dashboard. Approved for closure.'
    }
    res_review = client.post(f'/api/v1/cmo/reports/{report_id}/review/', review_payload)
    assert res_review.status_code == 200, f"Review failed: {res_review.data}"

    # Verify grievance status in DB is officially RESOLVED
    g_resolved = Grievance.objects.get(id=grievance_id)
    assert g_resolved.status == Grievance.Status.RESOLVED, f"Expected RESOLVED, got {g_resolved.status}"
    print(f"[14-15/17] CMO approved ATR. Grievance officially transitioned to: {g_resolved.status}.")

    # -------------------------------------------------------------
    # Step 16: Citizen sees final grievance status
    # -------------------------------------------------------------
    client.credentials(HTTP_AUTHORIZATION=f'Bearer {citizen_token}')
    res_cit_final = client.get(f'/api/v1/citizen/grievances/{grievance_id}/')
    assert res_cit_final.status_code == 200
    assert res_cit_final.data['status'] == 'RESOLVED'
    print(f"[16/17] Citizen observed grievance resolution.")

    # -------------------------------------------------------------
    # Step 17: Citizen submits feedback after resolution
    # -------------------------------------------------------------
    feedback_payload = {
        'rating': 5,
        'comments': 'Extremely prompt response and quality road restoration. Commendable governance!'
    }
    res_feedback = client.post(f'/api/v1/citizen/grievances/{grievance_id}/feedback/', feedback_payload)
    assert res_feedback.status_code == 201, f"Feedback submission failed: {res_feedback.data}"

    # Verify feedback in DB
    feedback_obj = CitizenFeedback.objects.get(grievance_id=grievance_id)
    assert feedback_obj.rating == 5
    print(f"[17/17] Citizen feedback recorded: {feedback_obj.rating}/5 stars.")
    print("=" * 70)
    print("ALL 17 END-TO-END WORKFLOW MILESTONES VERIFIED WITH ZERO ERRORS!")
    print("=" * 70)


if __name__ == '__main__':
    run_e2e_workflow_audit()
